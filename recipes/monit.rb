package 'monit'

service 'monit' do
  supports status: true, reload: true, restart: true
  action %i(enable start)
end

# sanity used the monit-ng cookbook, which replaced the package's /etc/monit/monitrc and /etc/default/monit:
# restore them since dpkg reinstalls missing conffiles with --force-confmiss
# (also when monitrc is missing, so a failed reinstall is retried on the next run)
execute 'restore monit conffiles' do
  command 'rm -f /etc/monit/monitrc /etc/default/monit && apt-get install --reinstall -y -o Dpkg::Options::=--force-confmiss monit'
  environment 'DEBIAN_FRONTEND' => 'noninteractive'
  only_if '[ ! -e /etc/monit/monitrc ] || head -n 1 /etc/monit/monitrc | grep -qx "# Generated by Chef"'
  notifies :restart, 'service[monit]'
end

alert = "set alert #{node['sanity']['root_email']} but not on { instance }" unless node['sanity']['root_email'].empty?

# /etc/monit/monitrc is left as the package ships it: it includes /etc/monit/conf.d/*, where these settings override its own
file '/etc/monit/conf.d/sanity.conf' do
  owner 'root'
  group 'root'
  mode '0600' # like /etc/monit/monitrc since it can contain credentials
  notifies :restart, 'service[monit]'
  content <<~MONIT
    # This file is managed by Chef, do not edit manually.
    set daemon 60
      with start delay #{node['sanity']['monit']['start_delay']}

    set mailserver localhost port 25

    set mail-format {
      from: monit@#{node['fqdn'] || 'localhost'}
      subject: $SERVICE $EVENT at $DATE
      message: Monit $ACTION $SERVICE at $DATE on $HOST: $DESCRIPTION.
      Yours sincerely,
      monit
    }

    #{alert}

    # needed by `monit status`
    set httpd port 2812 and
      use address localhost
      allow localhost
  MONIT
end

cmd = Mixlib::ShellOut.new('df -x devtmpfs -x tmpfs -x overlay --output=target')
cmd.run_command
cmd.error! # raise an exception if it didn't exit with 0
filesystems = cmd.stdout.lines.map(&:strip).drop(1)

check_filesystems = filesystems.map do |filesystem|
  name = filesystem[1..-1] # cannot start with a slash
  name = 'root' if name.empty?
  space_usage = node['sanity']['monit']['filesystem'][filesystem]
  space_usage ||= node['sanity']['monit']['filesystem']['/']

  "check filesystem #{name} with path #{filesystem}\nif space usage > #{space_usage} then alert"
end.join("\n")

file '/etc/monit/conf.d/system.conf' do
  owner 'root'
  group 'root'
  mode '0444'
  notifies :reload, 'service[monit]'
  content <<-MONIT.gsub(/^\s+/, '')
    check system $HOST
      if cpu usage > #{node['sanity']['monit']['cpu']} for #{node['sanity']['monit']['duration']} then alert
      if loadavg (5min) > #{node['sanity']['monit']['loadavg']} for #{node['sanity']['monit']['duration']} then alert
      if memory usage > #{node['sanity']['monit']['memory']} for #{node['sanity']['monit']['duration']} then alert
      if swap usage > #{node['sanity']['monit']['swap']} for #{node['sanity']['monit']['duration']} then alert
      if uptime > #{node['sanity']['monit']['uptime']} then alert

    #{check_filesystems}
  MONIT
end
